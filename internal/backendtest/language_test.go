package backendtest_test

import (
	"os"
	"path/filepath"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"

	"github.com/backbone81/golr/internal/backendtest"
)

// backendsLabel is on every spec which reads what a container produced. It is what "make test" deselects and what
// "make test-backends" selects, so which of the two kinds of run a spec belongs to is stated on the spec itself
// instead of in an environment variable which nothing in the tree mentions.
const backendsLabel = "backends"

// Every language the harness has a runner for is held to the whole corpus. This tree is built from the runner
// directories and the corpus directories, so a new language or a new case is a directory and never a spec written by
// hand. Nothing here knows a language: the list of them comes from the runner directories on disk, the code is
// generated by naming the language as the backend, and what a container does with a case is the language.sh of that
// language. Adding a language therefore never means editing Go.
//
// Every spec carries two labels. The "backends" label is what tells the two kinds of run apart: "make test" deselects
// it, because these specs need docker and take far longer than the unit tests, and "make test-backends" selects nothing
// else, because it has just produced the traces they read. The second label is the language, which is what
// "LANGUAGE=javascript make test-backends" narrows the run down with; it needs no lookup table because the name of the
// runner directory is at once the label, the compose service and the name of the backend.
//
// Every spec here only reads a file. The containers have already run by the time the suite starts, because
// "make test-backends" runs them before it runs the suite, so nothing in this tree needs a setup node and the specs are
// independent of each other. That is what keeps the report per case: one backend getting one case wrong is one failing
// spec named after the language, the case and the role.
var _ = Describe("Language backends", func() {
	// The languages are read while the spec tree is built, so that every language is a container of its own and a
	// failure names the language it belongs to.
	languages, err := backendtest.Languages()
	Expect(err).ToNot(HaveOccurred())

	for _, language := range languages {
		Describe(language, Label(backendsLabel, language), func() {
			for _, caseName := range goldenCaseNames() {
				It("reproduces the scanner trace of "+caseName, func() {
					expectTrace(language, caseName, backendtest.ScannerRole, scannerTraceFileName)
				})

				It("reproduces the parser trace of "+caseName, func() {
					expectTrace(language, caseName, backendtest.ParserRole, parserTraceFileName)
				})
			}
		})
	}
})

// expectTrace holds the trace a runner produced for one case and role against the trace committed for that case.
//
// Why a trace is missing or short is not repeated here. A generator which refused the grammar and a runner which threw
// both said so in the output of the container run, under the name of the case, which is where a reader looks for it.
//
// The two shape checks come before the comparison on purpose. Both failures make every single line of a diff mismatch
// for a reason the diff itself does not show, so reporting them by name is the difference between a one line fix and an
// afternoon. A raw carriage return means a runner wrote CRLF, and a missing final newline means it wrote its lines one
// at a time and lost the last one.
//
// UPDATE_GOLDEN deliberately has no effect here. A committed trace states what the Go reference produces, so rewriting
// one from the output of a runner would let a backend define its own expectation and the comparison would prove
// nothing.
func expectTrace(language string, caseName string, role string, goldenFileName string) {
	workPath, err := backendtest.WorkPath(language)
	Expect(err).ToNot(HaveOccurred())

	// A missing work directory means no container ever ran, which is a different failure from a run which produced
	// nothing for one case, and it is what a plain "go test ./internal/backendtest/..." runs into. It is reported by
	// name and before anything else, because the alternative is one unexplained failure per case.
	_, err = os.Stat(workPath)
	Expect(err).ToNot(HaveOccurred(),
		"there are no traces for %s, because the containers which produce them have not run.\n"+
			"Run 'make test-backends' to generate, compile and run the corpus in a container per language, or\n"+
			"'LANGUAGE=%s make test-backends' for this language alone. It runs these specs afterwards, while\n"+
			"'make test' leaves them out with --ginkgo.label-filter='!%s'.",
		language, language, backendsLabel)

	casePath := filepath.Join(workPath, caseName)

	actual, err := os.ReadFile(filepath.Join(casePath, role+backendtest.TraceFileSuffix))
	Expect(err).ToNot(HaveOccurred(),
		"the %s runner produced no %s trace for %s. What the generator and the runner said about that case is in the\n"+
			"output of the container run, which comes before these failures and names every case it worked on.",
		language, role, caseName)

	Expect(string(actual)).ToNot(ContainSubstring("\r"),
		"the %s trace contains a carriage return, which no canonical trace does", role)

	if len(actual) != 0 {
		Expect(string(actual)).To(HaveSuffix("\n"),
			"the %s trace does not end in a newline, which every canonical trace does", role)
	}

	expected, err := os.ReadFile(filepath.Join(goldenRootPath, caseName, goldenFileName))
	Expect(err).ToNot(HaveOccurred())
	Expect(string(actual)).To(Equal(string(expected)))
}
